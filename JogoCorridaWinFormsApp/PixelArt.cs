        private static readonly Dictionary<string, Bitmap> cache = [];

        public static IEnumerable<string> Nomes => Desenhos.Keys;

        /// <summary>Devolve o sprite como imagem (1 pixel do desenho = 1 pixel da imagem).</summary>
        public static Bitmap? Obter(string nome)
        {
            if (cache.TryGetValue(nome, out var pronto)) return pronto;
            if (!Desenhos.TryGetValue(nome, out var desenho)) return null;

            var linhas = desenho.Split('\n')
                                .Select(l => l.TrimEnd('\r', ' '))
                                .Select(l => l.TrimStart())
                                .Where(l => l.Length > 0)
                                .ToArray();

            // tira as linhas totalmente vazias de cima e de baixo, para a proporcao
            // do sprite bater com a caixa onde ele vai ser desenhado
            var conteudo = linhas.ToList();
            while (conteudo.Count > 0 && conteudo[0].All(c => c == '.' || c == ' ')) conteudo.RemoveAt(0);
            while (conteudo.Count > 0 && conteudo[^1].All(c => c == '.' || c == ' ')) conteudo.RemoveAt(conteudo.Count - 1);
            linhas = [.. conteudo];

            var largura = linhas.Max(l => l.Length);
            var bitmap = new Bitmap(largura, linhas.Length, PixelFormat.Format32bppArgb);

            for (int y = 0; y < linhas.Length; y++)
            {
                for (int x = 0; x < linhas[y].Length; x++)
                {
                    var letra = linhas[y][x];
                    if (letra == '.' || letra == ' ') continue;
                    if (!Paleta.TryGetValue(letra, out var cor)) continue;
                    bitmap.SetPixel(x, y, cor);
                }
            }

            cache[nome] = bitmap;
            return bitmap;
        }

        /// <summary>
        /// Desenha o sprite dentro da caixa, SEM borrar: cada pixel do desenho vira um
        /// quadrado. E isso que deixa a imagem com cara de pixel art de verdade.
        /// </summary>
        public static void Desenhar(Graphics g, string nome, RectangleF caixa, float inclinacao = 0)
        {
            var sprite = Obter(nome);
            if (sprite is null) return;

            var modoAnterior = g.InterpolationMode;
            var pixelAnterior = g.PixelOffsetMode;
            g.InterpolationMode = InterpolationMode.NearestNeighbor;
            g.PixelOffsetMode = PixelOffsetMode.Half;

            var estado = g.Save();
            if (Math.Abs(inclinacao) > 0.01f)
            {
                var centro = new PointF(caixa.X + caixa.Width / 2, caixa.Y + caixa.Height / 2);
                g.TranslateTransform(centro.X, centro.Y);
                g.RotateTransform(inclinacao);
                g.TranslateTransform(-centro.X, -centro.Y);
            }

            // mantem a proporcao do desenho: encaixa na largura da caixa e
            // apoia o sprite na base dela (os pes no chao)
            var altura = caixa.Width * sprite.Height / sprite.Width;
            var destino = new RectangleF(caixa.X, caixa.Bottom - altura, caixa.Width, altura);
            if (altura > caixa.Height)
            {
                var largura = caixa.Height * sprite.Width / sprite.Height;
                destino = new RectangleF(caixa.X + (caixa.Width - largura) / 2, caixa.Y, largura, caixa.Height);
            }

            g.DrawImage(sprite, destino);

            g.Restore(estado);
            g.InterpolationMode = modoAnterior;
            g.PixelOffsetMode = pixelAnterior;
        }

        /// <summary>Proporcao altura/largura do desenho, para a caixa nao distorcer.</summary>
        public static float Proporcao(string nome)
        {
            var sprite = Obter(nome);
            return sprite is null ? 1f : (float)sprite.Height / sprite.Width;
        }

        public static void Liberar()
        {
            foreach (var bitmap in cache.Values) bitmap.Dispose();
            cache.Clear();
        }

        /// <summary>
        /// Salva todos os sprites numa folha unica. Serve para conferir o desenho
        /// sem precisar abrir o jogo (usado durante o desenvolvimento).
        /// </summary>
        public static void SalvarFolhaDeTeste(string caminho, int escala = 8)
        {
            var nomes = Desenhos.Keys.ToList();
            var colunas = 6;
            var linhas = (int)Math.Ceiling(nomes.Count / (double)colunas);
            var celula = 18 * escala + 22;

            using var folha = new Bitmap(colunas * celula, linhas * celula);
            using var g = Graphics.FromImage(folha);
            using var fonte = new Font("Consolas", 9, FontStyle.Bold);

            g.Clear(Color.FromArgb(12, 10, 18));
            g.InterpolationMode = InterpolationMode.NearestNeighbor;
            g.PixelOffsetMode = PixelOffsetMode.Half;

            for (int i = 0; i < nomes.Count; i++)
            {
                var sprite = Obter(nomes[i]);
                if (sprite is null) continue;

                var x = i % colunas * celula + 8;
                var y = i / colunas * celula + 6;
                g.DrawImage(sprite, x, y, sprite.Width * escala, sprite.Height * escala);
                g.DrawString(nomes[i], fonte, Brushes.Yellow, x, y + 18 * escala);
            }

            folha.Save(caminho, ImageFormat.Png);
        }
